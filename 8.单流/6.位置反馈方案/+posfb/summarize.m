function summary=summarize(trials)
summary=upa.summarize(trials);n=height(summary);extras=cell(n,16);
for i=1:n
 t=trials(strcmp(trials.case_id,summary.case_id{i}),:);qe=t.coordinate_quantization_error_m;pe=t.estimation_error_m;
 extras(i,:)={t.experiment_id{1},t.coordinate_budget(1),t.coordinate_axis_bits{1},t.allocation_id{1},t.quantizer_domain_id{1},t.localizer_id{1},...
 sqrt(mean(pe.^2,'omitnan')),sqrt(mean(qe.^2,'omitnan')),sum(t.quantizer_overflow,'omitnan'),prctile(t.throughput_Mbps,5),...
 prctile(t.throughput_Mbps,50),prctile(t.throughput_Mbps,95),mean(t.UE_localization_condition,'omitnan'),...
 t.q_frequency(1),t.Q_phase(1),mean(t.coordinate_quantization_error_m,'omitnan')};
end
summary=[summary,cell2table(extras,'VariableNames',{'experiment_id','coordinate_budget','coordinate_axis_bits','allocation_id','quantizer_domain_id','localizer_id',...
 'estimation_RMSE_m','quantization_RMSE_m','quantizer_overflow_count','throughput_p05_Mbps','throughput_p50_Mbps','throughput_p95_Mbps','mean_localization_condition',...
 'q_frequency','Q_phase','mean_quantization_error_m'})];
end
